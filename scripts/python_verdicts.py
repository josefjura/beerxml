"""Record the Python validator's verdict on every sample, for each version.

The Rust crate's parity test (rust/tests/parity.rs) asserts that its strict
`validate` agrees with this table, so the two reference implementations
can't drift apart unnoticed.

Usage (from the repository root):

    python3 scripts/python_verdicts.py           # rewrite the table
    python3 scripts/python_verdicts.py --check   # fail if it is out of date
"""

import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

from lib.schema_parser import parse_xsd  # noqa: E402
from lib.validator import validate_file  # noqa: E402

SCHEMAS = {
    "1.0": "docs/spec/v1.0/beerxml-1.0.xsd",
    "1.1": "docs/spec/v1.1/beerxml-1.1.xsd",
}
SAMPLES = "samples"
TABLE = "rust/tests/fixtures/python_verdicts.tsv"


def samples():
    """Every sample, relative to samples/, with forward slashes, sorted."""
    found = []
    for root, _dirs, files in os.walk(os.path.join(REPO, SAMPLES)):
        for name in files:
            if name.endswith(".xml"):
                path = os.path.relpath(os.path.join(root, name), os.path.join(REPO, SAMPLES))
                found.append(path.replace(os.sep, "/"))
    return sorted(found)


def table():
    schemas = {v: parse_xsd(os.path.join(REPO, p)) for v, p in SCHEMAS.items()}
    lines = [
        "# Verdicts of the Python validator (lib/validator.py) on every sample.",
        "# Generated by scripts/python_verdicts.py; do not edit by hand.",
        "# sample\tversion\tverdict\terrors",
    ]
    for sample in samples():
        for version, schema in schemas.items():
            errors = validate_file(os.path.join(REPO, SAMPLES, sample), schema)
            verdict = "invalid" if errors else "valid"
            lines.append(f"{sample}\t{version}\t{verdict}\t{len(errors)}")
    return "\n".join(lines) + "\n"


def main():
    expected = table()
    path = os.path.join(REPO, TABLE)
    if "--check" in sys.argv[1:]:
        with open(path, encoding="utf-8") as f:
            if f.read() != expected:
                sys.exit(f"{TABLE} is out of date: run python3 scripts/python_verdicts.py")
        print(f"{TABLE} is up to date")
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(expected)
    print(f"wrote {TABLE}")


if __name__ == "__main__":
    main()
